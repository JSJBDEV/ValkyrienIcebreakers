// The value here should match an entry in the META-INF/mods.toml file
@Mod(ValkIB.MODID)
public class ValkIB
{
    // Define mod id in a common place for everything to reference
    public static final String MODID = "valkib";
    // Directly reference a slf4j logger
    private static final Logger LOGGER = LogUtils.getLogger();
    // Create a Deferred Register to hold Blocks which will all be registered under the "examplemod" namespace
    public static final DeferredRegister<Block> BLOCKS = DeferredRegister.create(ForgeRegistries.BLOCKS, MODID);
    // Create a Deferred Register to hold Items which will all be registered under the "examplemod" namespace
    public static final DeferredRegister<Item> ITEMS = DeferredRegister.create(ForgeRegistries.ITEMS, MODID);
    // Create a Deferred Register to hold CreativeModeTabs which will all be registered under the "examplemod" namespace
    // Creates a new Block with the id "examplemod:example_block", combining the namespace and path
    public static final RegistryObject<Block> ICEBREAKER = BLOCKS.register("ice_breaker", () -> new IceBreakerBlock(BlockBehaviour.Properties.of().mapColor(MapColor.STONE)));
    // Creates a new BlockItem with the id "examplemod:example_block", combining the namespace and path
    public static final RegistryObject<Item> ICEBREAKER_ITEM = ITEMS.register("ice_breaker", () -> new BlockItem(ICEBREAKER.get(), new Item.Properties()));

    public static final DeferredRegister<BlockEntityType<?>> BLOCK_ENTITIES = DeferredRegister.create(ForgeRegistries.BLOCK_ENTITY_TYPES, MODID);

    public static final RegistryObject<BlockEntityType<IceBreakerBlockEntity>> MY_BE = BLOCK_ENTITIES.register("ice_breaker", () -> BlockEntityType.Builder.of(IceBreakerBlockEntity::new, ICEBREAKER.get()).build(null));


    public static final TagKey<Block> BREAKABLES = TagKey.create(Registries.BLOCK, ResourceLocation.tryBuild("valkib","breakables"));
    // Creates a creative tab with the id "examplemod:example_tab" for the example item, that is placed after the combat tab

    public ValkIB(FMLJavaModLoadingContext context)
    {
        IEventBus modEventBus = context.getModEventBus();

        // Register the Deferred Register to the mod event bus so blocks get registered
        BLOCKS.register(modEventBus);
        // Register the Deferred Register to the mod event bus so items get registered
        ITEMS.register(modEventBus);
        // Register the Deferred Register to the mod event bus so tabs get registered
        BLOCK_ENTITIES.register(modEventBus);

        // Register ourselves for server and other game events we are interested in
        MinecraftForge.EVENT_BUS.register(this);
    }
}
